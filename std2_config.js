// ગ્રેડ નક્કી કરવાનું
function std2Grade(pct) {
  if (pct >= 80) return 'A';
  if (pct >= 65) return 'B';
  if (pct >= 50) return 'C';
  if (pct >= 35) return 'D';
  return 'E';
}

// એક subject નું ગણિત
// marks = ['A','B','C', '', ...]
function std2Calc(marks) {
  let a = 0, b = 0, c = 0;
  for (const m of marks) {
    if (m === 'A') a++;
    else if (m === 'B') b++;
    else if (m === 'C') c++;
  }
  const filled = a + b + c;
  const maxItems = marks.length;
  const points = a * 3 + b * 2 + c * 1;
  const maxPoints = maxItems * 3;
  const pct = maxPoints > 0 ? Math.round(points * 100 / maxPoints) : 0;
  return {
    a, b, c, filled, points, maxPoints, pct,
    grade: filled === maxItems ? std2Grade(pct) : ''
  };
}